#!/bin/sh
#
# Prints the licence texts of the third-party software that ships inside
# hoard: the Go modules compiled into the binary and the npm packages bundled
# into the web UI. Their licences ask for these notices to accompany binary
# distributions, so the output is put into the container image and into the
# release archives as THIRD_PARTY_NOTICES.md.
#
#   scripts/third-party-notices.sh [all|go|npm]     (default: all)
#
# Run from the repository root. "go" needs the Go toolchain and module cache,
# "npm" needs web/node_modules (npm ci). Plain POSIX sh: it also runs in the
# Alpine build stages of the Dockerfile.

set -eu

mode="${1:-all}"

# Prints the licence-like files of a directory under a heading.
emit() { # name, version, dir
  found=0
  printf '\n## %s %s\n' "$1" "$2"
  for f in "$3"/LICEN[CS]E* "$3"/COPYING* "$3"/NOTICE* "$3"/licen[cs]e* "$3"/UNLICENSE*; do
    [ -f "$f" ] || continue
    case "$(basename "$f")" in *3RD-PARTY* | *3rd-party*) continue ;; esac # the dependency's own dependency list
    found=1
    printf '\n### %s\n\n```text\n' "$(basename "$f")"
    sed 's/```/` ` `/g' "$f" # a fence inside a licence text would end the block early
    printf '\n```\n'
  done
  if [ "$found" -eq 0 ]; then
    echo "no licence file found for $1 in $3" >&2
    return 1
  fi
}

go_section() {
  printf '\n# Go modules compiled into the binary\n'
  goroot="$(go env GOROOT)"
  if [ -f "$goroot/LICENSE" ]; then
    emit "Go standard library and runtime" "" "$goroot"
  else # some distributions (Homebrew) ship Go without its licence file
    printf '\n## Go standard library and runtime\n\nBSD-3-Clause, Copyright The Go Authors. Full text: https://go.dev/LICENSE\n'
  fi
  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/hoard |
    LC_ALL=C sort -u |
    while read -r path version dir; do
      emit "$path" "$version" "$dir"
    done
}

npm_section() {
  printf '\n# npm packages bundled into the web UI\n'
  (cd web && npm ls --omit=dev --all --parseable 2>/dev/null) |
    grep '/node_modules/' | LC_ALL=C sort -u |
    while read -r dir; do
      name="$(node -p "require('$dir/package.json').name")"
      case "$name" in @types/* | csstype) continue ;; esac # type declarations only; nothing of them is bundled
      emit "$name" "$(node -p "require('$dir/package.json').version")" "$dir"
    done
}

header() {
  cat <<'EOF'
# Third-party notices

hoard is released under the MIT License (see LICENSE). It includes the
third-party software listed below, each under its own licence. This file is
generated by scripts/third-party-notices.sh.
EOF
}

case "$mode" in
  all) header; go_section; npm_section ;;
  go) header; go_section ;;
  npm) npm_section ;;
  *) echo "usage: $0 [all|go|npm]" >&2; exit 2 ;;
esac
