// Badges for the review status of an asset and the state of an asset request.
// Colours are tokens (--status-*) in styles/tokens.css, shown on /design.

import type { RequestStatus } from '../lib/types-work'

export const STATUS_LABEL: Record<string, string> = {
  draft: 'Draft',
  approved: 'Approved',
  final: 'Final',
  rework: 'Needs rework',
  rejected: 'Rejected',
  placeholder: 'Placeholder',
  superseded: 'Superseded',
}

const STATUS_HINT: Record<string, string> = {
  draft: 'Submitted, not reviewed yet',
  approved: 'Reviewed and approved',
  final: 'Final version',
  rework: 'Marked for another pass; a rework request is in the queue',
  rejected: 'Rejected',
  placeholder: 'Temporary stand-in generated by hoard, waiting for the real asset',
  superseded: 'Replaced by a newer asset',
}

/** Review status of an asset; renders nothing for an unreviewed asset. */
export function StatusBadge({ status, title }: { status: string; title?: string }) {
  if (!status) return null
  return (
    <span className="badge status-badge" data-status={status} title={title ?? STATUS_HINT[status]}>
      {STATUS_LABEL[status] ?? status}
    </span>
  )
}

const REQUEST_LABEL: Record<RequestStatus, string> = {
  open: 'Open',
  claimed: 'In progress',
  submitted: 'In review',
  done: 'Done',
  cancelled: 'Cancelled',
}

/** State of an asset request in the queue. */
export function RequestBadge({ status }: { status: RequestStatus }) {
  return (
    <span className="badge status-badge" data-status={`request-${status}`}>
      {REQUEST_LABEL[status] ?? status}
    </span>
  )
}

/** Statuses worth a mark on a library card (an unreviewed or draft asset needs none). */
export const CARD_STATUSES = ['approved', 'final', 'rework', 'rejected', 'placeholder', 'superseded']
