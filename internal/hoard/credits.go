package hoard

import (
	"context"
	"fmt"
	"net/url"
	"regexp"
	"sort"
	"strings"
	"time"
)

// CreditIssue is an asset whose credits cannot be written properly.
type CreditIssue struct {
	AssetID string `json:"asset_id"`
	Name    string `json:"name"`
	Problem string `json:"problem"`
}

// Credits is the generated CREDITS.md of a project.
type Credits struct {
	ProjectID      string        `json:"project_id"`
	Markdown       string        `json:"markdown"`
	AssetCount     int           `json:"asset_count"`
	NeedsAttention []CreditIssue `json:"needs_attention"`
}

var reSPDX = regexp.MustCompile(`^(CC0|CC-BY|MIT|Apache|OFL|GPL|LGPL|AGPL|BSD|MPL|ISC|Unlicense|Zlib|BSL|CDLA|ODbL|WTFPL|Artistic)[A-Za-z0-9.+-]*$`)

var reWWW = regexp.MustCompile(`(?i)\bwww\.`)

// stripInvisible removes bidirectional controls and zero-width characters,
// which could reorder or hide text in a credits file.
func stripInvisible(r rune) rune {
	switch {
	case r >= 0x202A && r <= 0x202E, r >= 0x2066 && r <= 0x2069, r >= 0x200B && r <= 0x200F, r == 0x2060, r == 0xFEFF, r == 0x00AD:
		return -1
	}
	return r
}

// mdEscape makes untrusted text inert in Markdown (and in HTML, which most
// Markdown renderers pass through): every character with a meaning is
// backslash-escaped, line breaks become spaces, invisible and bidi characters
// are dropped, and the characters that start GitHub-style autolinks (the colon
// of http:// and mailto:, the dot of www. and the @ of addresses) are escaped
// so that text never turns into a link on its own.
func mdEscape(s string) string {
	s = strings.Map(stripInvisible, strings.ToValidUTF8(s, ""))
	s = reWWW.ReplaceAllStringFunc(s, func(m string) string { return m[:3] + "\u0001" })
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\u0001':
			b.WriteString("\\.")
		case r == '\n' || r == '\r' || r == '\t':
			b.WriteByte(' ')
		case r < 0x20 || r == 0x7f:
		case strings.ContainsRune("\\`*_{}[]<>#!|~&:@", r):
			b.WriteByte('\\')
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return strings.TrimSpace(b.String())
}

// noLicense reports whether a license value says nothing.
func noLicense(lic string) bool {
	lic = strings.TrimSpace(lic)
	return lic == "" || strings.EqualFold(lic, "unknown")
}

// mdLink renders a URL as a Markdown autolink when it is a plain http(s) URL,
// and as escaped text otherwise (never as a link).
func mdLink(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}
	u, err := url.Parse(raw)
	if err == nil && (u.Scheme == "http" || u.Scheme == "https") && u.Host != "" &&
		!strings.ContainsAny(raw, " <>\"\\`\x00\r\n\t") && !strings.ContainsFunc(raw, func(r rune) bool { return r < 0x20 || r > 0x7e }) {
		return "<" + raw + ">"
	}
	return mdEscape(raw)
}

func licenseURL(lic, explicit string) string {
	if strings.TrimSpace(explicit) != "" {
		return explicit
	}
	if reSPDX.MatchString(lic) {
		return "https://spdx.org/licenses/" + lic + ".html"
	}
	return ""
}

// ProjectCredits writes CREDITS.md for the assets used in a project, grouped
// by license, plus a list of assets that need attention (no license, or a
// CC-BY license without attribution). Rejected and superseded assets are left
// out. All stored text is Markdown-escaped.
func (s *Service) ProjectCredits(ctx context.Context, projectID string) (*Credits, error) {
	p, err := s.GetProject(ctx, projectID)
	if err != nil {
		return nil, err
	}
	assets, err := s.projectAssets(ctx, projectID)
	if err != nil {
		return nil, err
	}
	c := &Credits{ProjectID: p.ID, NeedsAttention: []CreditIssue{}}
	groups := map[string][]*Asset{}
	for _, a := range assets {
		if a.Status == "rejected" || a.Status == "superseded" {
			continue
		}
		c.AssetCount++
		lic := strings.TrimSpace(a.License)
		if noLicense(lic) {
			lic = ""
			c.NeedsAttention = append(c.NeedsAttention, CreditIssue{a.ID, a.Name, "no license recorded"})
		} else if needsAttribution(lic) && strings.TrimSpace(a.Attribution) == "" {
			c.NeedsAttention = append(c.NeedsAttention, CreditIssue{a.ID, a.Name, "license " + lic + " requires attribution, none recorded"})
		}
		groups[lic] = append(groups[lic], a)
	}
	keys := make([]string, 0, len(groups))
	for k := range groups {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { // licensed groups first (alphabetical), unlicensed last
		if (keys[i] == "") != (keys[j] == "") {
			return keys[j] == ""
		}
		return strings.ToLower(keys[i]) < strings.ToLower(keys[j])
	})

	var b strings.Builder
	fmt.Fprintf(&b, "# Credits: %s\n\n", mdEscape(p.Name))
	fmt.Fprintf(&b, "Assets used in this project, grouped by license. Generated by hoard on %s (%d assets).\n", time.Now().UTC().Format("2006-01-02"), c.AssetCount)
	if c.AssetCount == 0 {
		b.WriteString("\nNo assets are recorded for this project.\n")
	}
	for _, lic := range keys {
		list := groups[lic]
		if lic == "" {
			b.WriteString("\n## No license recorded\n\n")
		} else {
			fmt.Fprintf(&b, "\n## %s\n\n", mdEscape(lic))
			if u := licenseURL(lic, ""); u != "" {
				fmt.Fprintf(&b, "License text: %s\n\n", mdLink(u))
			}
		}
		for _, a := range list {
			fmt.Fprintf(&b, "- **%s** (%s)", mdEscape(a.Name), a.Type)
			if a.Status == "placeholder" {
				b.WriteString(" [placeholder]")
			}
			if at := strings.TrimSpace(a.Attribution); at != "" {
				fmt.Fprintf(&b, "\n  - Credit: %s", mdEscape(at))
			}
			if a.Source != "" || a.SourceURL != "" {
				b.WriteString("\n  - Source: ")
				switch {
				case a.Source != "" && a.SourceURL != "":
					fmt.Fprintf(&b, "%s, %s", mdEscape(a.Source), mdLink(a.SourceURL))
				case a.Source != "":
					b.WriteString(mdEscape(a.Source))
				default:
					b.WriteString(mdLink(a.SourceURL))
				}
			}
			// A license link of the asset itself, when it differs from the group's default.
			if own := strings.TrimSpace(a.LicenseURL); own != "" && own != licenseURL(lic, "") {
				fmt.Fprintf(&b, "\n  - License: %s", mdLink(own))
			}
			b.WriteString("\n")
		}
	}
	if len(c.NeedsAttention) > 0 {
		b.WriteString("\n## Needs attention\n\nThese assets cannot be credited properly yet. Fix them in hoard before you ship.\n\n")
		for _, i := range c.NeedsAttention {
			fmt.Fprintf(&b, "- %s: %s\n", mdEscape(i.Name), mdEscape(i.Problem))
		}
	}
	c.Markdown = b.String()
	return c, nil
}
